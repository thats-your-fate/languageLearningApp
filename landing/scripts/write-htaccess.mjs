import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outDir = join(root, "out");
const htaccessPath = join(outDir, ".htaccess");

const htaccess = `# Generated by landing/scripts/write-htaccess.mjs
# Allows Apache hosting of the static Next export with clean child routes.

Options -MultiViews
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Serve real files directly.
  RewriteCond %{REQUEST_FILENAME} -f
  RewriteRule ^ - [L]

  # Serve exported directory indexes if any are present.
  RewriteCond %{REQUEST_FILENAME}/index.html -f
  RewriteRule ^(.+?)/?$ $1/index.html [L]

  # Serve clean routes such as /privacy from /privacy.html.
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_URI} ^/(.+?)/?$
  RewriteCond %{DOCUMENT_ROOT}/%1.html -f
  RewriteRule ^(.+?)/?$ /%1.html [L]

  # Let Apache return the generated static 404 for everything else.
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule ^ /404.html [L]
</IfModule>
`;

await mkdir(outDir, { recursive: true });
await writeFile(htaccessPath, htaccess);
console.log(`Wrote ${htaccessPath}`);
